// Generates src/api/gen/*.ts from ../api/openapi/*.yaml (the contract source of truth).
// `--check` fails when the committed files differ from a fresh generation.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const SPECS = ['common', 'identity', 'catalog', 'order'];
const specDir = new URL('../../api/openapi/', import.meta.url);
const outDir = new URL('../src/api/gen/', import.meta.url);
const check = process.argv.includes('--check');
const header = '/* Generated by `npm run gen:api` from api/openapi. Do not edit by hand. */\n\n';

let stale = false;
await mkdir(outDir, { recursive: true });
for (const name of SPECS) {
  // emptyObjectsUnknown: ProductInput is `allOf: [ProductPatch, {required: [...]}]`; the default renders the
  // required-only member as Record<string, never>, which turns every ProductPatch field into `never`.
  // defaultNonNullable: false keeps fields with a `default` (e.g. SkuInput.active) optional in request bodies.
  const ast = await openapiTS(new URL(`${name}.yaml`, specDir), { emptyObjectsUnknown: true, defaultNonNullable: false });
  const code = header + astToString(ast);
  const target = new URL(`${name}.ts`, outDir);
  if (check) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current !== code) {
      console.error(`src/api/gen/${name}.ts is out of date; run \`npm run gen:api\`.`);
      stale = true;
    }
  } else {
    await writeFile(target, code);
    console.log(`wrote src/api/gen/${name}.ts`);
  }
}
if (stale) process.exit(1);
